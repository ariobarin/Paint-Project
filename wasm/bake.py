def rust_str(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def rgba(surface):
    """A surface's pixels as an RGBA (or RGB, if it has no alpha) PIL image, exactly."""
    w, h = surface.get_size()
    if surface.get_flags() & pygame.SRCALPHA:
        return Image.frombytes("RGBA", (w, h), pygame.image.tobytes(surface, "RGBA"))
    return Image.frombytes("RGB", (w, h), pygame.image.tobytes(surface, "RGB"))


def save_png(name, image):
    image.save(OUT / name, optimize=True)
    return name


def baked_image(name, surface):
    return f'Baked {{ png: include_bytes!("{save_png(name, rgba(surface))}") }}'


# fit_img_to_rect / scale_img_to_rect in src/utils.py, without the blit
def fitted(img, rect):
    scale = min(rect.width / img.get_width(), rect.height / img.get_height())
    return pygame.transform.smoothscale(img, (int(img.get_width() * scale), int(img.get_height() * scale)))


def covering(img, rect):
    scale = max(rect.width / img.get_width(), rect.height / img.get_height())
    return pygame.transform.smoothscale(img, (int(img.get_width() * scale), int(img.get_height() * scale)))


def centred(rect, surface):
    return rect.centerx - surface.get_width() // 2, rect.centery - surface.get_height() // 2


