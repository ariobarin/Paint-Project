"""Bake the game's images and text for the WebAssembly build, with pygame itself.

Everything the game draws that never changes (smoothscaled icons and previews, the scaled backgrounds,
the static text, the font metrics for the colour code) is computed here, once, by the same pygame calls
the Python version makes at runtime, so the browser build shows the same pixels without shipping a
font renderer or pygame's smoothscale. Run from anywhere:

    uv run wasm/bake.py [--lossless]

It writes wasm/baked/ (generated, not committed): what the Rust code builds in, and in baked/site/ the
files the page fetches. --lossless keeps the backgrounds as PNG instead of WebP, for comparing frames
with the Python version pixel for pixel.
"""

