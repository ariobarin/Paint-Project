# --- static text (write_centered_text in src/utils.py): each line's coverage and where it goes ---
pygame.font.init()


def centred_text(text, rect):
    lines = text.split("\n")
    low, high = 1, max(rect.width, rect.height)
    while low < high:
        mid = (low + high + 1) // 2
        font = pygame.font.Font(None, mid)
        sizes = [font.size(line) for line in lines]
        if sum(s[1] for s in sizes) <= rect.height and max(s[0] for s in sizes) <= rect.width:
            low = mid
        else:
            high = mid - 1
    font = pygame.font.Font(None, low)
    sizes = [font.size(line) for line in lines]
    text_height = sum(s[1] for s in sizes)
    y = rect.y + (rect.height - text_height) // 2
    out = []
    for i, (line, size) in enumerate(zip(lines, sizes)):
        surface = font.render(line, True, (255, 255, 255))
        out.append((surface, rect.x + (rect.width - size[0]) // 2, y + i * size[1]))
    return out


