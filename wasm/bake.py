rust.append("];")
rust.append(f"// the sizes a colour code can end on; their glyphs' coverage is in hex_glyphs.bin, in this order")
rust.append(f"pub const HEX_SIZES: [usize; {len(reachable)}] = {reachable};")
rust.append('pub const HEX_GLYPH_COVERAGE: &[u8] = include_bytes!("hex_glyphs.bin");')

